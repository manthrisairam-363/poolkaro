export function getAreasForCity(cityKey) {
  return CITIES[cityKey]?.areas?.map(a => a.name) || []
}

export function getZones(cityKey) {
  const areas = CITIES[cityKey]?.areas || []
  const zones = {}
  areas.forEach(a => {
    if (!zones[a.zone]) zones[a.zone] = []
    zones[a.zone].push(a.name)
  })
  return zones
}
